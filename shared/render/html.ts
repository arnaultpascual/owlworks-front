/** Build-time HTML helpers (Node only). */
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { SITE, PLACEHOLDERS, locales, type Link, type PageId, type SiteContent } from '../content.ts';

/** Escape for text and attribute values. Content strings may carry inline HTML on purpose: don't escape those. */
export const esc = (s: string | number) =>
  String(s).replace(/&(?!(?:[a-z]+|#\d+);)/gi, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

/** Strip tags/entities for attributes (alt, aria-label, meta). */
export const plain = (s: string) =>
  s
    .replace(/<[^>]+>/g, '')
    .replace(/&nbsp;/g, ' ')
    .replace(/&amp;/g, '&')
    .replace(/\s+/g, ' ')
    .trim();

/** Wrap unfilled [PLACEHOLDERS] so they are impossible to miss. */
export const markPlaceholders = (html: string) =>
  html.replace(/(<[^>]*>)|([^<]+)/g, (_m, tag: string | undefined, text: string | undefined) =>
    tag ?? (text ?? '').replace(/\[([A-ZÀ-Ü][A-ZÀ-Üa-zà-ü _/—–-]+)\]/g, '<span class="placeholder">[$1]</span>'),
  );

export const isPlaceholder = (v: string) => /^\[.*\]$/.test(v) || v === '';

export function link(l: Link, attrs = '', newTabText = '(nouvel onglet)'): string {
  const ext = l.external ? ` target="_blank" rel="noopener"` : '';
  const sr = l.external ? `<span class="sr-only"> ${newTabText}</span>` : '';
  return `<a href="${esc(l.href)}"${ext} ${attrs}>${l.label}${sr}</a>`;
}

export function mailto(c: SiteContent, attrs = ''): string {
  const email = SITE.email;
  if (isPlaceholder(email)) return `<a href="#contact" ${attrs}><span class="placeholder">${esc(PLACEHOLDERS.CONTACT_EMAIL)}</span></a>`;
  return `<a href="mailto:${esc(email)}" ${attrs}>${esc(email)}</a>`;
}

/* ----------------------------------------------------------------- images */

interface ImgEntry {
  width: number;
  height: number;
  widths: number[];
  ratio: number;
}
const manifestPath = fileURLToPath(new URL('../img/manifest.json', import.meta.url));
let manifest: Record<string, ImgEntry> | null = null;
const getManifest = (): Record<string, ImgEntry> => (manifest ??= JSON.parse(readFileSync(manifestPath, "utf8")));

export interface PictureOptions {
  alt: string;
  /** the `sizes` attribute: how wide the image is displayed */
  sizes?: string;
  className?: string;
  imgClass?: string;
  /** above the fold: eager + fetchpriority=high */
  priority?: boolean;
  attrs?: string;
}

/** <picture> with AVIF + WebP srcsets generated by scripts/images.mjs. */
export function picture(name: string, o: PictureOptions): string {
  const m: ImgEntry | undefined = getManifest()[name];
  if (!m) throw new Error(`picture(): unknown image "${name}" — run npm run images`);
  const set = (fmt: string) => m.widths.map((w) => `/shared/img/${name}-${w}.${fmt} ${w}w`).join(', ');
  const largest = m.widths[m.widths.length - 1];
  const h = Math.round(largest / m.ratio);
  const sizes = o.sizes ?? '100vw';
  const load = o.priority ? 'loading="eager" fetchpriority="high"' : 'loading="lazy"';
  return (
    `<picture${o.className ? ` class="${o.className}"` : ''}>` +
    `<source type="image/avif" srcset="${set('avif')}" sizes="${sizes}">` +
    `<source type="image/webp" srcset="${set('webp')}" sizes="${sizes}">` +
    `<img src="/shared/img/${name}-${largest}.webp" width="${largest}" height="${h}" alt="${esc(plain(o.alt))}" ${load} decoding="async"${o.imgClass ? ` class="${o.imgClass}"` : ''} ${o.attrs ?? ''}>` +
    `</picture>`
  );
}

export const imageInfo = (name: string): ImgEntry => getManifest()[name];

/* ------------------------------------------------------------------ head */

export interface HeadOptions {
  title?: string;
  description?: string;
  /** path on owlworks.dev, e.g. '/' or '/legal/mentions-legales/' */
  path: string;
  themeColor?: string;
  /** fonts to preload (file names in shared/fonts) */
  preloadFonts?: string[];
  /** extra raw tags */
  extra?: string;
  /** Open Graph locale (default fr_FR) */
  ogLocale?: string;
  /** the same page in other languages: { fr: '/legal/…', en: '/en/legal/…' } */
  alternates?: Record<string, string>;
  noindex?: boolean;
}

/**
 * Swaps <html class="no-js"> for "js" before the first paint, so the JS layout is the first
 * layout (no shift when the module script arrives). Its sha256 is allowed in the CSP (_headers).
 */
export const EARLY_JS = `document.documentElement.classList.replace('no-js','js')`;

/** hreflang alternates of a page: every language, French as the default */
export function alternatesFor(page: PageId): Record<string, string> {
  return { fr: locales.fr.paths[page], en: locales.en.paths[page], 'x-default': locales.fr.paths[page] };
}

/** <head> content: SEO, Open Graph, icons. Everything https and absolute where it must be. */
export function head(c: SiteContent, o: HeadOptions): string {
  const title = o.title ?? c.meta.title;
  const description = o.description ?? c.meta.description;
  const url = SITE.url + o.path;
  const og = `${SITE.url}/og-image${c.locale === 'en' ? '-en' : ''}.png`;
  const fonts = (o.preloadFonts ?? [])
    .map((f) => `<link rel="preload" href="/shared/fonts/${f}" as="font" type="font/woff2" crossorigin>`)
    .join('');
  return [
    `<meta charset="utf-8">`,
    `<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">`,
    `<script>${EARLY_JS}</script>`,
    `<title>${esc(plain(title))}</title>`,
    `<meta name="description" content="${esc(plain(description))}">`,
    `<link rel="canonical" href="${url}">`,
    o.noindex ? `<meta name="robots" content="noindex">` : '',
    `<meta name="theme-color" content="${o.themeColor ?? SITE.colors.night}">`,
    `<meta name="color-scheme" content="light dark">`,
    `<meta name="author" content="OwlWorks">`,
    PLACEHOLDERS.GOOGLE_SITE_VERIFICATION ? `<meta name="google-site-verification" content="${esc(PLACEHOLDERS.GOOGLE_SITE_VERIFICATION)}">` : '',
    `<meta property="og:type" content="website">`,
    `<meta property="og:site_name" content="OwlWorks">`,
    `<meta property="og:locale" content="${o.ogLocale ?? c.ogLocale}">`,
    `<meta property="og:locale:alternate" content="${c.locale === 'fr' ? 'en_US' : 'fr_FR'}">`,
    ...Object.entries(o.alternates ?? {}).map(([l, p]) => `<link rel="alternate" hreflang="${l}" href="${SITE.url}${p}">`),
    `<meta property="og:url" content="${url}">`,
    `<meta property="og:title" content="${esc(plain(title))}">`,
    `<meta property="og:description" content="${esc(plain(description))}">`,
    `<meta property="og:image" content="${og}">`,
    `<meta property="og:image:width" content="1200">`,
    `<meta property="og:image:height" content="630">`,
    `<meta property="og:image:alt" content="${esc(c.meta.ogAlt)}">`,
    `<meta name="twitter:card" content="summary_large_image">`,
    `<meta name="twitter:image" content="${og}">`,
    `<link rel="icon" href="/favicon.ico" sizes="32x32">`,
    `<link rel="icon" href="/favicon.svg" type="image/svg+xml">`,
    `<link rel="apple-touch-icon" href="/apple-touch-icon.png">`,
    `<link rel="manifest" href="/site.webmanifest">`,
    fonts,
    o.extra ?? '',
  ]
    .filter(Boolean)
    .join('\n    ');
}

/** JSON-LD for the organisation (helps the Play Console / Search Console story). */
export function orgJsonLd(): string {
  const data = {
    '@context': 'https://schema.org',
    '@type': 'Organization',
    name: 'OwlWorks',
    legalName: 'OwlWorks SASU',
    url: SITE.url,
    logo: `${SITE.url}/icon-512.png`,
    sameAs: [SITE.github, SITE.atlassianVendor, ...(SITE.linkedin ? [SITE.linkedin] : [])],
    vatID: PLACEHOLDERS.TVA,
    address: { '@type': 'PostalAddress', streetAddress: '105 rue Dragon', postalCode: '13006', addressLocality: 'Marseille', addressCountry: 'FR' },
  };
  return `<script type="application/ld+json">${JSON.stringify(data)}</script>`;
}

/* --------------------------------------------------------------- github */

export interface GithubRepo {
  name: string;
  description: string;
  url: string;
  homepage: string;
  stars: number;
  forks: number;
  language: string;
  topics: string[];
}

/** Pinned repos (scripts/github.mjs), merged with the French copy of content.ts. */
export function pinnedRepos(c: SiteContent) {
  const read = (f: string) => {
    try {
      return JSON.parse(readFileSync(fileURLToPath(new URL(`../data/${f}`, import.meta.url)), 'utf8'));
    } catch {
      return null;
    }
  };
  const data = read('github.json') ?? read('github.fallback.json') ?? { repos: [] };
  return (data.repos as GithubRepo[]).map((r) => {
    const copy = c.openSource.repos[r.name];
    return {
      ...r,
      pitch: copy?.pitch ?? r.description,
      detail: copy?.detail ?? '',
      stack: copy?.stack ?? (r.language ? [r.language] : []),
      verb: copy?.verb ?? '',
    };
  });
}

/** "OwlWorks on the Atlassian Marketplace" line under ReadSeal's status (text only, no logo). */
export function vendorLink(c: SiteContent, cls: string): string {
  const l = c.projects.readseal.links?.[0];
  if (!l) return '';
  return `<p class="${cls}">${link({ ...l, label: `${l.label}<span aria-hidden="true"> ↗</span>` }, '', c.a11y.newTab)}</p>`;
}

/** Store links of a product: a real link once published, "App Store · bientôt" until then (text only, no badges).
 *  While no store is live, the status already says "bientôt", so it is only read out. */
export function storeLinks(c: SiteContent, p: { stores?: { name: string; href: string }[] }, cls: string): string {
  if (!p.stores?.length) return '';
  const soonCls = p.stores.some((st) => st.href) ? 'store-soon' : 'sr-only';
  const items = p.stores
    .map((st) =>
      st.href
        ? `<li>${link({ label: `${st.name}<span aria-hidden="true"> ↗</span>`, href: st.href, external: true }, 'class="store"', c.a11y.newTab)}</li>`
        : `<li><span class="store is-soon">${st.name}<span class="${soonCls}"> · ${c.ui.storeSoon}</span></span></li>`,
    )
    .join('');
  return `<ul class="${cls}" role="list" aria-label="${c.ui.storesLabel}">${items}</ul>`;
}
